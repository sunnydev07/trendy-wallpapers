import fs from "node:fs";
import path from "node:path";

const store = JSON.parse(fs.readFileSync(".demo-wallpapers.json", "utf8"));
const licensed = store.filter((w) => w.source_type === "licensed_stock");

fs.mkdirSync("public/curated/originals", { recursive: true });
fs.mkdirSync("public/curated/thumbs", { recursive: true });
fs.mkdirSync("src/data", { recursive: true });

const curated = [];
let moved = 0;
for (const w of licensed) {
  const ext = path.extname(w.r2_original_key).replace(".", "") || "jpg";
  const srcOriginal = path.join(".uploads", `${w.slug}.${ext}`);
  const srcThumb = path.join(".uploads", `${w.slug}.webp`);
  if (!fs.existsSync(srcOriginal) || !fs.existsSync(srcThumb)) {
    console.log("SKIP missing files", w.slug);
    continue;
  }
  fs.copyFileSync(srcOriginal, path.join("public/curated/originals", `${w.slug}.${ext}`));
  fs.copyFileSync(srcThumb, path.join("public/curated/thumbs", `${w.slug}.webp`));
  moved++;
  curated.push({
    ...w,
    r2_original_key: `curated/originals/${w.slug}.${ext}`,
    r2_thumb_key: `curated/thumbs/${w.slug}.webp`,
    thumb_url: `/curated/thumbs/${w.slug}.webp`,
    preview_url: `/api/download?slug=${encodeURIComponent(w.slug)}&w=1200&format=webp&preview=1`,
  });
}

const header = `import type { Wallpaper } from "@/types/wallpaper";

/**
 * Source-controlled curated wallpapers (real photographs, freely licensed).
 * Originals live in public/curated/originals, thumbnails in public/curated/thumbs.
 * Generated by scripts/migrate-curated.mjs — do not edit by hand.
 */
export const CURATED_WALLPAPERS: Wallpaper[] = `;

fs.writeFileSync(
  "src/data/curated-wallpapers.ts",
  header + JSON.stringify(curated, null, 2) + ";\n"
);

// Keep only ephemeral AI experiments in the local demo store.
const remaining = store.filter((w) => w.source_type !== "licensed_stock");
fs.writeFileSync(".demo-wallpapers.json", JSON.stringify(remaining));

console.log(`moved ${moved} originals+thumbs; curated module has ${curated.length}; demo store now ${remaining.length}`);
